import type { Metadata } from "next";
import { DentalImplantsClientChrome } from "./DentalImplantsClientChrome";
import { SITE_URL } from "@/lib/site-data";
import {
  breadcrumbJsonLd,
  organizationJsonLd,
  websiteJsonLd,
} from "@/lib/structured-data";
import { BREADCRUMBS, IMPLANT_FAQ, PAGE_PATH } from "@/lib/dental-implants-page";
import { OG_IMAGE_ALT, OG_IMAGE_SIZE } from "@/lib/og-image";

/* ------------------------------------------------------------------
   /treatments/dental-implants — hand-built page (no [slug] route, no
   shared treatment template).

   og:image / twitter:image: the site's default card image is generated by
   app/opengraph-image.tsx and app/twitter-image.tsx, but Next only
   attaches those files to the root route, so they are referenced here
   explicitly (verified: /treatments and /about emit no og:image).

   JSON-LD: BreadcrumbList + MedicalWebPage + FAQPage (built from
   IMPLANT_FAQ, the same array the visible accordion renders). No
   lastReviewed (no reviewer is recorded yet), no reviews, no ratings.
   ------------------------------------------------------------------ */

const title = "Dental Implants in Nampally & Mehdipatnam | Neodent";
const description =
  "Dental implant treatment at Neodent Dental Hospital in Nampally and Mehdipatnam, Hyderabad: the stages, healing, risks and questions to ask your dentist.";
const url = `${SITE_URL}${PAGE_PATH}`;

export const metadata: Metadata = {
  title: { absolute: title },
  description,
  alternates: {
    canonical: PAGE_PATH,
  },
  openGraph: {
    type: "website",
    locale: "en_IN",
    url: PAGE_PATH,
    title,
    description,
    images: [{ url: "/opengraph-image", ...OG_IMAGE_SIZE, alt: OG_IMAGE_ALT }],
  },
  twitter: {
    card: "summary_large_image",
    title,
    description,
    images: [{ url: "/twitter-image", ...OG_IMAGE_SIZE, alt: OG_IMAGE_ALT }],
  },
};

const jsonLd = [
  breadcrumbJsonLd(BREADCRUMBS),
  {
    "@context": "https://schema.org",
    "@type": "MedicalWebPage",
    name: "Dental implants",
    url,
    description,
    inLanguage: "en-IN",
    about: {
      "@type": "MedicalProcedure",
      name: "Dental implant",
    },
    isPartOf: { "@id": websiteJsonLd["@id"] },
    publisher: { "@id": organizationJsonLd["@id"] },
  },
  {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: IMPLANT_FAQ.map(({ question, answer }) => ({
      "@type": "Question",
      name: question,
      acceptedAnswer: { "@type": "Answer", text: answer },
    })),
  },
];

export default function Page() {
  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />
      <DentalImplantsClientChrome />
    </>
  );
}
